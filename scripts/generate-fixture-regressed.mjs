// Generates fixtures/synthetic-session-regressed.ndjson deterministically: a
// "regressed run" variant of the synthetic fixture for the session comparison
// view (src/compare) tests and demos.
//
// SYNTHETIC DATA: derived by a fixed transform from the output of
// scripts/generate-fixture.mjs (itself seeded), not from Sonder Runtime or
// Sonder-Inference. Every event keeps `producer.synthetic: true`. Relative to
// the base fixture the variant has, by construction:
//   - slower prefill (higher TTFT) and ~1.4x longer inter-token gaps (lower
//     decode tok/s) for req_005..req_010;
//   - 25% larger prompt_tokens on every request;
//   - two extra tool retries (synthetic.search_v2 fails twice in req_004);
//   - a second, critical context budget guard (req_007);
//   - kv.reused / kv.allocated lookups (cache hit rate falls from 75% to 25%
//     after req_004) and `cost_usd` on request outcomes with a
//     `cost_budget_usd` on session.started (the base fixture reports neither);
//   - topology changes: tool `synthetic.search` is replaced by
//     `synthetic.search_v2` and the critic calls a new `synthetic.rerank` tool.
//
// Usage: node scripts/generate-fixture-regressed.mjs [output-path] [base-path]
import { spawnSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

export const REGRESSED_SESSION_ID = "ses_synthetic_0002";
export const REGRESSED_RUN_ID = "run_synthetic_0002";
export const REGRESSED_EVENT_PREFIX = "evt_reg_";

/** $ per 1M tokens used for the synthetic `cost_usd` attribute. */
const PRICE_IN = 0.6;
const PRICE_OUT = 2.4;
const COST_BUDGET_USD = 0.01;

function requestIndex(event) {
    const m = /^req_(\d+)$/.exec(event.request_id ?? "");
    return m ? Number(m[1]) - 1 : -1;
}

function scalePrompt(attributes) {
    if (typeof attributes.prompt_tokens !== "number") {
        return attributes;
    }
    return { ...attributes, prompt_tokens: Math.round(attributes.prompt_tokens * 1.25) };
}

/**
 * Applies the regression transform to base fixture events (replay order).
 * Pure and deterministic: same input, same output. Returns new event objects
 * with fresh ids and contiguous sequences.
 */
export function regressFixtureEvents(baseEvents) {
    if (baseEvents.length === 0) {
        return [];
    }
    const mono0 = baseEvents[0].mono_ns;
    const wall0 = Date.parse(baseEvents[0].wall_time);
    const drafts = [];
    const push = (ms, template, eventType, extra = {}, attributes = {}) => {
        drafts.push({ ms, order: drafts.length, template, eventType, extra, attributes });
    };
    let shift = 0;
    const lastToken = new Map();
    const tokenCount = new Map();
    const promptFor = new Map();
    const genFor = new Map();

    for (const e of baseEvents) {
        const baseMs = Math.round((e.mono_ns - mono0) / 1e6);
        const i = requestIndex(e);
        const slow = i >= 4;
        const t = e.event_type;
        let attributes = scalePrompt(e.attributes);

        if (t === "inference.prefill.completed" && slow) {
            shift += 140 + 20 * (i - 4);
        }
        if (t === "inference.token.generated") {
            const prev = lastToken.get(e.request_id);
            if (slow && prev !== undefined) {
                shift += Math.round((baseMs - prev) * 0.4);
            }
            lastToken.set(e.request_id, baseMs);
            tokenCount.set(e.request_id, (tokenCount.get(e.request_id) ?? 0) + 1);
        }
        if (typeof attributes.prompt_tokens === "number" && e.request_id) {
            promptFor.set(e.request_id, attributes.prompt_tokens);
        }
        if (t === "session.started") {
            attributes = {
                ...attributes,
                variant: "regressed",
                cost_budget_usd: COST_BUDGET_USD,
                note: "Synthetic regressed-run variant generated by scripts/generate-fixture-regressed.mjs; not model telemetry.",
            };
        }
        if (t === "tool.called" && attributes.tool === "synthetic.search") {
            attributes = { ...attributes, tool: "synthetic.search_v2" };
        }
        if ((t === "request.completed" || t === "request.failed") && e.request_id) {
            const gen = typeof attributes.generated_tokens === "number" ? attributes.generated_tokens : 0;
            genFor.set(e.request_id, gen);
            const prompt = promptFor.get(e.request_id) ?? 0;
            const cost = Math.round(((prompt * PRICE_IN + gen * PRICE_OUT) / 1e6) * 1e6) / 1e6;
            attributes = { ...attributes, cost_usd: cost };
        }

        const ms = baseMs + shift;

        // tc_1 (synthetic.search_v2 in req_004) fails twice before completing.
        if (t === "tool.completed" && attributes.tool_call_id === "tc_1") {
            const call = (id, attempt) => ({ tool_call_id: id, tool: "synthetic.search_v2", args: "[redacted]", attempt });
            push(ms, e, "tool.failed", {}, { tool_call_id: "tc_1", error: "synthetic rate limit", duration_ms: 179 });
            push(ms + 2, e, "retry.scheduled", {}, { tool_call_id: "tc_1", attempt: 2, backoff_ms: 50 });
            push(ms + 60, e, "tool.called", {}, call("tc_1_r2", 2));
            push(ms + 140, e, "tool.failed", {}, { tool_call_id: "tc_1_r2", error: "synthetic rate limit", duration_ms: 80 });
            push(ms + 142, e, "retry.scheduled", {}, { tool_call_id: "tc_1_r2", attempt: 3, backoff_ms: 50 });
            push(ms + 200, e, "tool.called", {}, call("tc_1_r3", 3));
            push(ms + 280, e, "tool.completed", {}, { tool_call_id: "tc_1_r3", duration_ms: 80, result: "[redacted]" });
            shift += 285;
            continue;
        }

        push(ms, e, t, {}, attributes);

        if (t === "request.started" && e.request_id && i >= 0) {
            // Four kv lookups per request: 3 hits early, 1 hit from req_005 on.
            const hits = i < 4 ? 3 : 1;
            for (let k = 0; k < 4; k += 1) {
                const hit = k < hits;
                push(ms + 1, e, hit ? "kv.reused" : "kv.allocated", { device_id: "dev_gpu0" }, hit ? { block: k, avoided_prefill_tokens: 128 } : { block: k, reason: "miss" });
            }
        }
        if (t === "inference.token.generated") {
            const n = tokenCount.get(e.request_id);
            if (i === 6 && n === 10) {
                push(ms + 2, e, "guard.budget_pressure", { device_id: null }, { budget: "context", used_fraction: 0.97 });
            }
            if (i === 7 && n === 5) {
                push(ms + 1, e, "tool.called", { device_id: null }, { tool_call_id: "tc_rr_1", tool: "synthetic.rerank", args: "[redacted]" });
                push(ms + 121, e, "tool.completed", { device_id: null }, { tool_call_id: "tc_rr_1", duration_ms: 120, result: "[redacted]" });
                shift += 125;
            }
        }
    }

    drafts.sort((a, b) => a.ms - b.ms || a.order - b.order);
    return drafts.map((d, seq) => {
        const tpl = d.template;
        const event = {
            ...tpl,
            event_id: `${REGRESSED_EVENT_PREFIX}${String(seq + 1).padStart(6, "0")}`,
            sequence: seq,
            event_type: d.eventType,
            wall_time: new Date(wall0 + d.ms).toISOString(),
            mono_ns: mono0 + d.ms * 1_000_000,
            session_id: REGRESSED_SESSION_ID,
            run_id: tpl.run_id ? REGRESSED_RUN_ID : null,
            ...d.extra,
            attributes: d.attributes,
        };
        return event;
    });
}

/** Base fixture NDJSON text -> regressed variant NDJSON text. */
export function regressFixtureText(baseText) {
    const events = baseText
        .split("\n")
        .filter((line) => line.trim() !== "")
        .map((line) => JSON.parse(line));
    return regressFixtureEvents(events).map((e) => JSON.stringify(e)).join("\n") + "\n";
}

const here = dirname(fileURLToPath(import.meta.url));
export const DEFAULT_BASE_PATH = resolve(here, "..", "fixtures/synthetic-session.ndjson");
export const DEFAULT_REGRESSED_PATH = resolve(here, "..", "fixtures/synthetic-session-regressed.ndjson");

/** Writes the variant; generates the base fixture first if it is missing. Returns the event count. */
export function writeRegressedFixture(outPath = DEFAULT_REGRESSED_PATH, basePath = DEFAULT_BASE_PATH) {
    if (!existsSync(basePath)) {
        const gen = spawnSync(process.execPath, [resolve(here, "generate-fixture.mjs"), basePath], { stdio: "inherit" });
        if (gen.status !== 0) {
            throw new Error("generate-fixture.mjs failed");
        }
    }
    const text = regressFixtureText(readFileSync(basePath, "utf8"));
    mkdirSync(dirname(outPath), { recursive: true });
    writeFileSync(outPath, text, "utf8");
    return text.split("\n").filter(Boolean).length;
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
    const out = process.argv[2] ? resolve(process.cwd(), process.argv[2]) : DEFAULT_REGRESSED_PATH;
    const base = process.argv[3] ? resolve(process.cwd(), process.argv[3]) : DEFAULT_BASE_PATH;
    const n = writeRegressedFixture(out, base);
    console.log(`wrote ${n} synthetic (regressed variant) events to ${out}`);
}
